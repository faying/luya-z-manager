#!/usr/bin/env python3
"""Pre-render the hand-back explanation frame's text lines (u60-sentinel.md §5 new 1, DR8).

The sentinel carries no font engine: each line is rendered here once, as 4-bit alpha, run-length
coded, and written as Rust source (src/frame_text.rs). The font is the touch screen's CJK fallback,
Resource Han Rounded (SIL OFL 1.1: the generated glyph data is a derivative and keeps the licence,
see ../FRAME-FONT-LICENSE). Run it again when a line changes:

  docker run --rm -v "$PWD":/w -v <dir with u60-cjk-fallback.ttf>:/f:ro python:3-slim \\
    sh -c 'pip -q install pillow==11.3.0 && python3 /w/crates/luyaz-sentinel/frame/gen.py /f/u60-cjk-fallback.ttf /w/crates/luyaz-sentinel/src/frame_text.rs'

(from source/manager; the font is in the install kit's fonts/ or on the device under
/data/luyaz/ui/fonts/). Output is deterministic for one font file and Pillow version.
"""
import hashlib
import sys

from PIL import Image, ImageDraw, ImageFont

# (size class, text). Size classes: 0 = title, 1 = body. Words from docs/ui-glossary.md
# (触屏界面 / Screen UI, 原厂界面 / stock UI) and the ui-gave-up SMS.
LINES = {
    "ZH": [
        (0, "屏幕界面连续打不开"),
        (1, "已换成原厂界面"),
        (1, "上网不受影响"),
        (1, "长按屏幕右下角 3 秒"),
        (1, "可以换回来"),
    ],
    "EN": [
        (0, "Screen UI kept failing"),
        (1, "Switching to the stock UI"),
        (1, "Internet is not affected"),
        (1, "Hold the bottom-right"),
        (1, "corner 3 s to go back"),
    ],
}
SIZES = [26, 20]
MAX_W = 300  # the panel is 320 wide


def render(text, size, font_path):
    font = ImageFont.truetype(font_path, size)
    l, t, r, b = font.getbbox(text)
    w, h = r - l + 2, size + size // 3
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((1 - l, (h - (b - t)) // 2 - t), text, font=font, fill=255)
    if w > MAX_W:
        sys.exit(f"line too wide ({w} px > {MAX_W}): {text}")
    return w, h, [p >> 4 for p in img.getdata()]


def rle(vals):
    """(alpha 0-15, run 1-255) pairs packed as one byte each: alpha << 4 | (run - 1) >> 4 would
    lose range, so two bytes per run: alpha, run."""
    out = []
    i = 0
    while i < len(vals):
        v = vals[i]
        n = 1
        while i + n < len(vals) and vals[i + n] == v and n < 255:
            n += 1
        out += [v, n]
        i += n
    return out


def main():
    font, out = sys.argv[1], sys.argv[2]
    digest = hashlib.sha256(open(font, "rb").read()).hexdigest()[:16]
    src = [
        "// Generated by frame/gen.py from Resource Han Rounded (SIL OFL 1.1, see FRAME-FONT-LICENSE);",
        f"// font sha256 {digest}. Do not edit: change LINES in gen.py and run it again.",
        "",
        "use crate::frame::Line;",
        "",
    ]
    for lang, lines in LINES.items():
        src.append(f"pub const {lang}: &[Line] = &[")
        for cls, text in lines:
            w, h, vals = render(text, SIZES[cls], font)
            data = rle(vals)
            src.append(f"    // {text}")
            src.append(f"    Line {{ title: {str(cls == 0).lower()}, w: {w}, h: {h}, rle: &[")
            for k in range(0, len(data), 24):
                src.append("        " + ", ".join(str(x) for x in data[k:k + 24]) + ",")
            src.append("    ] },")
        src.append("];")
        src.append("")
    open(out, "w").write("\n".join(src))


if __name__ == "__main__":
    main()
