// Regenerate src/icons.rs from @phosphor-icons/react's path tables (bold + fill weights); the package
// comes from crates/luyaz-web/package.json (`npm ci` there once), from anywhere:
//   node crates/luyaz-web/tools/gen-icons.mjs
import { writeFileSync, readFileSync } from "node:fs";

const defs = new URL("../node_modules/@phosphor-icons/react/dist/defs/", import.meta.url).pathname;
// every icon src/icons.rs has now (the route table's came from the old web's routes.ts until X13;
// a new one: add its name to this list)
const current = readFileSync(new URL("../src/icons.rs", import.meta.url), "utf8");
const names = new Set(["House", "ChartLine", "SquaresFour", "GearSix", "MagnifyingGlass", "SignOut", "CaretLeft", "CaretRight", "Translate", "X", "ArrowClockwise", "Play", "Stop", "EnvelopeOpen", "Trash", "PaperPlaneRight", "ArrowLeft"]);
for (const m of current.matchAll(/\("(\w+)", (?:true|false)\)/g)) names.add(m[1]);

function weight(src, w) {
  const start = src.indexOf(`"${w}",`);
  if (start < 0) throw new Error("no weight " + w);
  const end = src.indexOf("\n  ]", start);
  const block = src.slice(start, end);
  const els = [...block.matchAll(/createElement\(\s*"(\w+)",\s*\{([^}]*)\}/g)];
  return els.map(([, tag, attrs]) => {
    if (tag !== "path") throw new Error(`${tag} element, not handled`);
    return `<path d="${/d: "([^"]+)"/.exec(attrs)[1]}"/>`;
  }).join("");
}

let out = "// Generated by tools/gen-icons.mjs from @phosphor-icons/react. Do not edit.\n\n/// Inner SVG markup (viewBox 0 0 256 256) for a Phosphor icon, bold or fill weight.\npub fn path(name: &str, fill: bool) -> &'static str {\n    match (name, fill) {\n";
for (const n of [...names].sort()) {
  const src = readFileSync(`${defs}${n}.es.js`, "utf8");
  out += `        (${JSON.stringify(n)}, false) => r#"${weight(src, "bold")}"#,\n`;
  out += `        (${JSON.stringify(n)}, true) => r#"${weight(src, "fill")}"#,\n`;
}
out += "        _ => \"\",\n    }\n}\n";
out += `\n/// Every icon in this file.\npub const NAMES: &[&str] = &[${[...names].sort().map((n) => JSON.stringify(n)).join(", ")}];\n`;
writeFileSync(new URL("../src/icons.rs", import.meta.url), out);
console.log(names.size, "icons");
