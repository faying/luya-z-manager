#!/bin/sh
# Regenerate src/bindings.rs and csrc/static_fns.c with bindgen 0.72.1 / clang 19 in a
# throwaway container (the shared build image stays without libclang).
#   rs/lvgl-sys/regen.sh [--check]     --check: fail if the committed files differ
# Needs the docker volume u60-spike-src with the patched LVGL (lvgl/) and FreeType (freetype/):
# rs/setup-src.sh.
# SPDX-License-Identifier: MIT
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
OUT=$(mktemp -d)
docker run --rm -v u60-spike-src:/s:ro -v "$ROOT/lv_conf.h":/conf/lv_conf.h:ro -v "$OUT":/out \
    -v u60-cargo-registry:/usr/local/cargo/registry rust:1.99.0 bash -c '
set -e
apt-get update -qq >/dev/null && apt-get install -y -qq libclang-dev clang >/dev/null 2>&1
rustup component add rustfmt >/dev/null 2>&1
cargo install -q bindgen-cli --version 0.72.1 >/dev/null 2>&1
printf "#include \"lvgl.h\"\n#include \"src/libs/freetype/lv_freetype.h\"\n" > /tmp/wrap.h
bindgen /tmp/wrap.h --use-core --no-layout-tests --allowlist-function "lv_.*" --allowlist-type "lv_.*" \
    --allowlist-var "LV_.*" --no-doc-comments --default-enum-style moduleconsts --experimental \
    --wrap-static-fns --wrap-static-fns-path /out/static_fns -o /out/bindings.rs -- \
    -DLV_CONF_INCLUDE_SIMPLE -I/conf -I/s/lvgl -I/s/freetype/include'
{
    printf '/* Generated by bindgen --wrap-static-fns (rs/lvgl-sys/regen.sh): LVGL'"'"'s static inline functions as real symbols. */\n#include "lvgl.h"\n#include "src/libs/freetype/lv_freetype.h"\n'
    tail -n +2 "$OUT/static_fns.c"
} >"$OUT/static_fns.c.fixed"
if [ "${1:-}" = --check ]; then
    cmp -s "$OUT/bindings.rs" "$HERE/src/bindings.rs" && cmp -s "$OUT/static_fns.c.fixed" "$HERE/csrc/static_fns.c" \
        || { echo "lvgl-sys: bindings out of date, run rs/lvgl-sys/regen.sh"; rm -rf "$OUT"; exit 1; }
    echo "lvgl-sys: bindings up to date"
else
    cp "$OUT/bindings.rs" "$HERE/src/bindings.rs"
    cp "$OUT/static_fns.c.fixed" "$HERE/csrc/static_fns.c"
fi
rm -rf "$OUT"
