use std::path::PathBuf;

/// The C string literals of one row, as written between the quotes; None for NULL.
fn fields(line: &str) -> Vec<Option<String>> {
    let b = line.as_bytes();
    let (mut out, mut i) = (Vec::new(), 0);
    while i < b.len() {
        if b[i] == b'"' {
            let start = i + 1;
            i += 1;
            while b[i] != b'"' {
                i += if b[i] == b'\\' { 2 } else { 1 };
            }
            out.push(Some(line[start..i].to_string()));
        } else if line[i..].starts_with("NULL") {
            out.push(None);
            i += 3;
        }
        i += 1;
    }
    out
}

/// What a C literal means, for sorting by the bytes strcmp sees (only \" \\ \n occur).
fn unescape(s: &str) -> String {
    s.replace("\\n", "\n").replace("\\\"", "\"").replace("\\\\", "\\")
}

fn main() {
    let dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let inc = dir.join("lang/en.inc");
    println!("cargo:rerun-if-changed={}", inc.display());
    let text = std::fs::read_to_string(&inc).expect("lang/en.inc");
    let mut rows: Vec<(String, String, Option<String>)> = Vec::new();
    for line in text.lines().filter(|l| l.trim_start().starts_with("{ \"")) {
        let f = fields(line);
        assert!(f.len() == 3 && f[0].is_some() && f[1].is_some(), "lang_en.inc: {line}");
        rows.push((f[0].clone().unwrap(), f[1].clone().unwrap(), f[2].clone()));
    }
    rows.sort_by_key(|r| unescape(&r.0));
    let mut out = String::from("// generated by build.rs from lang/en.inc\npub static ROWS: &[(&str, &str, Option<&str>)] = &[\n");
    for (zh, en, other) in &rows {
        let o = other.as_ref().map_or("None".to_string(), |s| format!("Some(\"{s}\")"));
        out += &format!("    (\"{zh}\", \"{en}\", {o}),\n");
    }
    out += "];\n";
    std::fs::write(PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("lang_en.rs"), out).unwrap();
}
