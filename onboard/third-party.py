#!/usr/bin/env python3
"""Write THIRD-PARTY.md for the install kit: every third-party piece that ends up on the device.

Three sources, each read from what is actually shipped, not typed by hand:
  - Rust crates: `cargo metadata --locked --format-version 1` (JSON file), normal
    dependencies reachable from the four device binaries. Platform-gated deps for
    other operating systems are dropped; anything left over is listed (over-listing
    is safe, under-listing is not).
  - eSIM bundle: the license field in .PKGINFO of each .apk named in alpine.lock.
  - Everything else: onboard/third-party.list (checked against upstream by hand).

Usage: third-party.py --cargo-metadata M.json --alpine-lock L --apk-dir D --list F [--kit DIR] [-o OUT]
       --check: exit 1 when a crate or package has no license field.
"""
import argparse, glob, io, json, os, re, sys, tarfile

ROOTS = ("luyaz-core", "luyaz-web", "luyaz-sentinel", "luyaz-ui")
OTHER_OS = re.compile(r"windows|macos|ios|android|wasm|wasi|redox|hermit|fuchsia|solaris|illumos|haiku|freebsd|netbsd|openbsd|dragonfly|apple|darwin")


def crates(meta_path):
    meta = json.load(open(meta_path))
    pkgs = {p["id"]: p for p in meta["packages"]}
    members = set(meta["workspace_members"])
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    todo = [i for i in members if pkgs[i]["name"] in ROOTS]
    if len(todo) != len(ROOTS):
        sys.exit("third-party.py: device crates missing from metadata: %s" % sorted(set(ROOTS) - {pkgs[i]["name"] for i in todo}))
    seen = set()
    while todo:
        i = todo.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            kinds = [k for k in d["dep_kinds"] if k["kind"] is None]  # normal deps only; build/dev deps never ship
            if kinds and any(not (k["target"] and OTHER_OS.search(k["target"])) for k in kinds):
                todo.append(d["pkg"])
    out = []
    for i in seen - members:
        p = pkgs[i]
        out.append((p["name"], p["version"], p.get("license") or "", p.get("repository") or ""))
    return sorted(out, key=lambda r: (r[0].lower(), r[1]))


def apks(lock, apk_dir):
    out = []
    for line in open(lock):
        f = line.split()
        if len(f) != 4 or line.startswith("#"):
            continue
        _, name, ver, _ = f
        path = os.path.join(apk_dir, "%s-%s.apk" % (name, ver))
        info = {}
        if not os.path.isfile(path):
            out.append((name, ver, "", ""))
            continue
        # an .apk is several gzip streams back to back; the second holds .PKGINFO
        with open(path, "rb") as fh:
            data = fh.read()
        for start in [m.start() for m in re.finditer(b"\x1f\x8b\x08", data)]:
            try:
                with tarfile.open(fileobj=io.BytesIO(data[start:]), mode="r:gz") as t:
                    m = t.extractfile(".PKGINFO")
                    if m:
                        for kv in m.read().decode().splitlines():
                            k, _, v = kv.partition(" = ")
                            info.setdefault(k, v)
                        break
            except (tarfile.TarError, KeyError, OSError, EOFError):
                continue
        out.append((name, ver, info.get("license", ""), info.get("url", "")))
    return out


def static(path, kit):
    """Rows of the hand-checked list; with --kit, only those whose files are in this kit."""
    out = []
    for line in open(path):
        if line.strip() and not line.startswith("#"):
            r = line.rstrip("\n").split("|")
            if kit:
                where = r[4].split(",")[0].split()[-1]  # "linked into payload/x" → payload/x
                if not glob.glob(os.path.join(kit, where.rstrip("/"))):
                    continue
            out.append(r)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cargo-metadata", required=True)
    ap.add_argument("--alpine-lock", required=True)
    ap.add_argument("--apk-dir", required=True)
    ap.add_argument("--list", required=True)
    ap.add_argument("--kit", help="kit directory: drop hand-listed rows whose files are not in it")
    ap.add_argument("-o", "--out")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    c, k, s = crates(a.cargo_metadata), apks(a.alpine_lock, a.apk_dir), static(a.list, a.kit)
    missing = [r[0] for r in c + k if not r[2]]
    w = []
    w.append("# Third-party components in the Luya-Z install kit\n")
    w.append("Generated by `onboard/third-party.py`; do not edit. Luya-Z itself is under the "
             "PolyForm Noncommercial License 1.0.0 (see LICENSE). The components below keep their own licenses.\n")
    w.append("Copyleft parts (GPL-3.0, AGPL-3.0, LGPL) are shipped unmodified as upstream built them; "
             "their source is at the upstream address listed, at the version listed.\n")
    w.append("## Bundled programs, data and fonts\n")
    w.append("| Component | Version | License | Upstream | In the kit | Checked against |")
    w.append("|---|---|---|---|---|---|")
    for r in s:
        w.append("| " + " | ".join(r) + " |")
    w.append("\n## eSIM bundle (Alpine Linux packages, `scripts/esim/alpine.lock`)\n")
    w.append("| Package | Version | License | Upstream |")
    w.append("|---|---|---|---|")
    for r in k:
        w.append("| %s | %s | %s | %s |" % r)
    w.append("\n## Rust crates linked into luyaz-core, luyaz-web, luyaz-sentinel, luyaz-ui (%d)\n" % len(c))
    w.append("| Crate | Version | License | Repository |")
    w.append("|---|---|---|---|")
    for r in c:
        w.append("| %s | %s | %s | %s |" % r)
    text = "\n".join(w) + "\n"
    if a.out:
        open(a.out, "w").write(text)
    else:
        sys.stdout.write(text)
    if missing:
        print("third-party.py: no license field: %s" % ", ".join(missing), file=sys.stderr)
        if a.check:
            sys.exit(1)


if __name__ == "__main__":
    main()
